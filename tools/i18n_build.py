# -*- coding: utf-8 -*-
"""Write assets/i18n.js from tools/i18n_src.py. Fails on duplicate or empty entries."""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from i18n_src import T  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), '..', 'assets', 'i18n.js')


def main():
    seen, bad = set(), []
    for row in T:
        ko = row[0]
        if len(row) != 3 or not all(row):
            bad.append('incomplete: %r' % (row,))
        if ko in seen:
            bad.append('duplicate: %r' % ko)
        seen.add(ko)
    if bad:
        print('\n'.join(bad))
        return 1
    data = {'ja': {r[0]: r[1] for r in T}, 'zh': {r[0]: r[2] for r in T}}
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('/* Generated by tools/i18n_build.py from tools/i18n_src.py. Do not edit. */\n')
        fh.write('window.LAB_I18N=' + json.dumps(data, ensure_ascii=False, indent=0) + ';\n')
    print('i18n.js: %d strings x 2 languages' % len(T))
    return 0


if __name__ == '__main__':
    sys.exit(main())
